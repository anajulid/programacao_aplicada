#include <iostream>

using namespace std;

int main() {
	int a = 5; // declaração e inicialização de uma variável inteira
	double b = 3.14; // declaração e inicialização de uma variável de ponto flutuante
	char c = 'A'; // declaração e inicialização de uma variável de caractere
	
	int soma = a + 2; // expressão e atribuição
	double area = b * a; // expressão e atribuição
	
	//printar resultado das operações 
	cout << "Soma: " << soma << endl;
	cout << "Area: " << area << endl;
	cout << "Caractere: " << c << endl;
	
	return 0;
}
