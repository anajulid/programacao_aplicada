#include <iostream>

using namespace std;

int main() {
	
	float num1, num2;
	
	cout << "Digite o primeiro numero: " << endl;
	cin >> num1;
	cout << "Digite o segundo numero: " << endl;
	cin >> num2;
	
	cout << "Soma: " << num1 + num2 << endl;
	cout << "Subtracao: " << num1 - num2 << endl;
	cout << "Multiplicacao: " << num1 * num2 << endl;
	cout << "Divisao: " << num1 / num2 << endl;
	
	return 0;
}
